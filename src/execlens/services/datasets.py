"""Application service: build synthetic ExecLens datasets.

A dataset is generated in three steps, all seeded and deterministic:

1. a synthetic Level-1 market (quotes and trades) for every instrument;
2. parent orders sampled per instrument and session;
3. fills produced by simulating each order with the strategy named in its
   ``strategy`` column (IMMEDIATE / TWAP / VWAP / POV), using the same fill
   model as the Strategy Lab. VWAP schedules come from prior-session volume
   profiles, never from the traded session.
"""

from __future__ import annotations

from typing import Final

from pydantic import BaseModel, ConfigDict, Field

from execlens import __version__
from execlens.data.synthetic import MarketConfig, OrderConfig, generate_market, generate_orders
from execlens.data.validation import ExecutionDataset
from execlens.simulation.simulator import (
    SimulationConfig,
    build_strategies,
    fills_to_frame,
    market_views,
    simulate_orders,
)
from execlens.simulation.vwap import VolumeProfile

DISCLAIMER: Final = (
    "Synthetic data generated by ExecLens for demonstration and testing. "
    "It is not real market data, and all fills are simulated."
)


class DatasetSpec(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    market: MarketConfig = Field(default_factory=MarketConfig)
    orders: OrderConfig = Field(default_factory=OrderConfig)
    simulation: SimulationConfig = Field(default_factory=SimulationConfig)


PRESETS: Final[dict[str, DatasetSpec]] = {
    # Small enough to commit (data/sample): one hour, six instruments.
    "sample": DatasetSpec(
        market=MarketConfig(session_seconds=3_600, seed=42),
        orders=OrderConfig(
            orders_per_symbol_per_session=40, horizons_seconds=(300, 600, 900, 1_200)
        ),
    ),
    # One full synthetic trading day, used by `execlens demo`.
    "demo": DatasetSpec(
        market=MarketConfig(seed=2026),
        orders=OrderConfig(orders_per_symbol_per_session=60),
    ),
    # Benchmark scale: two full days (> 1M quotes) and > 100k fills.
    "benchmark": DatasetSpec(
        market=MarketConfig(n_sessions=2, seed=1),
        orders=OrderConfig(orders_per_symbol_per_session=450),
    ),
}


def preset(name: str) -> DatasetSpec:
    try:
        return PRESETS[name]
    except KeyError:
        raise ValueError(f"unknown preset {name!r}; choose from {sorted(PRESETS)}") from None


def volume_profiles(spec: DatasetSpec) -> dict[str, VolumeProfile]:
    """Expected intraday volume profile per symbol, built from prior sessions only.

    Takes the spec, not the generated market: VWAP schedules cannot depend on
    the sessions they trade in.
    """
    return {
        instrument.symbol: VolumeProfile.from_history(
            instrument,
            session_seconds=spec.market.session_seconds,
            bucket_seconds=spec.simulation.profile_bucket_seconds,
            n_sessions=spec.simulation.profile_sessions,
            seed=spec.market.seed,
        )
        for instrument in spec.market.universe
    }


def generate_dataset(spec: DatasetSpec) -> ExecutionDataset:
    """Generate market, orders and simulated fills for ``spec``."""
    market = generate_market(spec.market)
    orders = generate_orders(spec.market, spec.orders)
    executions = simulate_orders(
        orders,
        market_views(market.quotes, market.trades, spec.simulation),
        build_strategies(spec.simulation, profiles=volume_profiles(spec)),
        spec.simulation,
    )
    metadata = {
        "synthetic": True,
        "disclaimer": DISCLAIMER,
        "generator": f"execlens {__version__}",
        "spec": spec.model_dump(mode="json"),
        "scenarios": {i.symbol: i.params.model_dump(mode="json") for i in spec.market.universe},
    }
    return ExecutionDataset.validated(
        quotes=market.quotes,
        trades=market.trades,
        orders=orders,
        fills=fills_to_frame(executions),
        metadata=metadata,
    )
